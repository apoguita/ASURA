#!/usr/bin/env python3
"""Write the path-finding cases both sides run: the reference's finder and this repo's port.

The cases come from `tools/map-config.sql` -- the generated catalogue of the reference's own maps, with
the spawn point each one puts a client down at. For every map row:

  * the spawn point to itself (the trivial case: same trapezoid, one waypoint);
  * eight offsets around it: four cardinal, four diagonal, two of them far enough to leave the map's
    bounding box. Some of those are reachable and some are not, which is the point -- the reference
    *refuses* walks it cannot make, and so must the port.

The offsets are whole numbers so both sides parse the same decimal into the same float.

Usage:
  python tools/gen-path-cases.py [--out PATH] [--check]

This file stays ASCII-only (docs/HANDOFF.md).
"""

import argparse
import io
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CATALOGUE = os.path.join(REPO, "tools", "map-config.sql")
DEFAULT_OUT = os.path.join(REPO, "crates", "asura-world", "tests", "fixtures", "path-cases.txt")

# A generated catalogue row: (map, type, blob, spawn count, x, y, plane, 'name'), followed by a comma.
ROW_RE = re.compile(
    r"^\s*\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,"
    r"\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(\d+)\s*,\s*'(.*)'\s*\)"
)

# Offsets from the spawn point, as (dx, dy). The last two are deliberately far enough to fall outside the
# map's bounding box, so the run also measures a refusal.
OFFSETS = (
    (0, 0),
    (1200, 0),
    (-1200, 0),
    (0, 1200),
    (0, -1200),
    (2000, 1500),
    (-2000, -1500),
    (30000, 30000),
)


def rows(path):
    with io.open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = ROW_RE.match(line)
            if match:
                yield {
                    "map_id": int(match.group(1)),
                    "blob": int(match.group(3)),
                    "x": float(match.group(5)),
                    "y": float(match.group(6)),
                    "plane": int(match.group(7)),
                    "name": match.group(8).replace("''", "'"),
                }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalogue", default=DEFAULT_CATALOGUE)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if not os.path.exists(args.catalogue):
        sys.stderr.write("no catalogue at %s\n" % args.catalogue)
        return 2

    lines = [
        "# Generated by tools/gen-path-cases.py from %s. Do not edit."
        % os.path.relpath(args.catalogue, REPO).replace("\\", "/"),
        "# One case per line: blob src_x src_y src_plane dst_x dst_y dst_plane.",
        "# Whole-number coordinates, so both sides parse the same decimal into the same float.",
    ]
    cases = 0
    for row in rows(args.catalogue):
        for dx, dy in OFFSETS:
            lines.append(
                "0x%08X %d %d %d %d %d %d"
                % (
                    row["blob"],
                    round(row["x"]),
                    round(row["y"]),
                    row["plane"],
                    round(row["x"]) + dx,
                    round(row["y"]) + dy,
                    row["plane"],
                )
            )
            cases += 1

    if cases == 0:
        sys.stderr.write("%s has no map rows\n" % args.catalogue)
        return 1

    generated = "\n".join(lines) + "\n"

    if args.check:
        if not os.path.exists(args.out):
            sys.stderr.write("no cases file at %s\n" % args.out)
            return 1
        existing = io.open(args.out, "r", encoding="utf-8", newline="\n").read()
        if existing != generated:
            sys.stderr.write(
                "the path cases are out of date; regenerate with python tools/gen-path-cases.py\n"
            )
            return 1
        print("the path cases are current: %s (%d case(s))" % (args.out, cases))
        return 0

    with io.open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)
    print("wrote %s: %d case(s)" % (args.out, cases))
    return 0


if __name__ == "__main__":
    sys.exit(main())
