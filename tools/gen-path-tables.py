#!/usr/bin/env python3
"""Generate the path finder's fixed-point lookup tables from the reference's `GmPaths.c`.

The reference does not call the FPU for a reciprocal or a square root: `PathReciproc` and `PathSqrt` are
256-entry tables of float *bit patterns* combined with integer arithmetic. That means the search's costs,
and therefore which trapezoids it visits and which waypoints it produces, depend on these tables exactly.
A port that used `1.0 / x` and `x.sqrt()` would be "the same algorithm" and a different path.

So they are read out of the reference rather than typed, the same way the decompressor's tables are.

Usage:
  python tools/gen-path-tables.py [--gwps PATH] [--out PATH] [--check]

This file stays ASCII-only (docs/HANDOFF.md).
"""

import argparse
import io
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GWPS = os.path.join(os.path.dirname(REPO), "PreSearing")
DEFAULT_OUT = os.path.join(REPO, "crates", "asura-world", "src", "path_tables.rs")


def read(path):
    with io.open(path, "r", encoding="utf-8", errors="replace") as handle:
        return handle.read()


def braced(text, start):
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : index]
    raise SystemExit("unbalanced braces")


def lookup_table(text, function, expected=256):
    """The `LookupTable` declared inside one function of `GmPaths.c`."""
    start = text.index("float %s(float value)" % function)
    match = re.search(r"LookupTable\s*\[[^\]]*\]\s*=\s*\{", text[start:])
    if not match:
        raise SystemExit("%s has no LookupTable" % function)
    body = braced(text, start + match.end() - 1)
    values = re.findall(r"0x[0-9A-Fa-f]+", body)
    if len(values) != expected:
        raise SystemExit(
            "%s's LookupTable has %d values, expected %d" % (function, len(values), expected)
        )
    return values


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gwps", default=DEFAULT_GWPS)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    path = os.path.join(args.gwps, "code", "OpenTyria", "GmPaths.c")
    if not os.path.exists(path):
        sys.stderr.write("no reference at %s\n" % path)
        return 2
    text = read(path)

    reciprocal = lookup_table(text, "PathReciproc")
    square_root = lookup_table(text, "PathSqrt")

    lines = [
        "//! Generated by `tools/gen-path-tables.py` from the reference's `GmPaths.c`. Do not edit.",
        "//!",
        "//! `PathReciproc` and `PathSqrt` are table-driven in the reference: 256 entries of float bit patterns,",
        "//! combined by integer arithmetic. The search's costs come out of these tables, so a port using the",
        "//! FPU's own division and square root would visit different trapezoids and return different waypoints.",
        "",
        "/// `PathReciproc`'s `LookupTable` (`GmPaths.c`).",
        "pub const RECIPROCAL: [u32; %d] = [%s];" % (len(reciprocal), ", ".join(reciprocal)),
        "",
        "/// `PathSqrt`'s `LookupTable` (`GmPaths.c`).",
        "pub const SQUARE_ROOT: [u32; %d] = [%s];" % (len(square_root), ", ".join(square_root)),
        "",
    ]
    generated = "\n".join(lines)

    # rustfmt reflows these long arrays, so the file on disk is the formatted form. Formatting the
    # generated text the same way is what makes --check a comparison of content rather than of layout.
    def formatted(source):
        import tempfile

        with tempfile.NamedTemporaryFile(
            "w", suffix=".rs", delete=False, encoding="utf-8", newline="\n"
        ) as handle:
            handle.write(source)
            temporary = handle.name
        try:
            subprocess.run(
                ["rustfmt", "--edition", "2021", temporary], check=True, capture_output=True
            )
            return read(temporary)
        finally:
            os.unlink(temporary)

    generated = formatted(generated)

    if args.check:
        if not os.path.exists(args.out):
            sys.stderr.write("no generated file at %s\n" % args.out)
            return 1
        if formatted(read(args.out)) != generated:
            sys.stderr.write(
                "the path finder's tables are out of date with the reference; regenerate with "
                "python tools/gen-path-tables.py\n"
            )
            return 1
        print("the path finder's tables are current: %s" % args.out)
        return 0

    with io.open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)
    print(
        "wrote %s: %d reciprocal entries, %d square-root entries"
        % (args.out, len(reciprocal), len(square_root))
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
