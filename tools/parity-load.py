#!/usr/bin/env python3
"""Measure the load stream against the reference's own trace: order and size, not content.

`tools/compare-load.py` diffs bytes, which is the right tool for finding a payload bug but a noisy one
for measuring parity: item ids, character names, unlock lists, tick values and spawn coordinates differ
by design, and every one of them shows up as a "problem". This tool measures the part that has to match
and can be pinned:

  * **missing**  a message the reference sends in the window that this server never sends;
  * **extra**    a message this server sends that the reference does not;
  * **size**     a message both send, at different lengths.

Alignment is `compare-load.py`'s rule -- each of our messages is matched to the next reference message
with the same header -- so a message sent twice, or out of order, is still visible.

`--fixture PATH` writes what was measured as a Rust constant, so the check does not need the reference
checkout at test time; `--check PATH` re-measures and fails if the reference has moved on.

Sources: GWPS's own `GWPS_TRACE=1` log (`SEND 0x017C   6 bytes : 7C 01 3F 3F 00 00` lines) and this
repo's `cargo run -p asura-world --example dump-load`.

This file stays ASCII-only (docs/HANDOFF.md).
"""

import argparse
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_REFERENCE = os.path.join(
    os.path.dirname(REPO), "PreSearing", "gwps-capture.log"
)
DEFAULT_FIXTURE = os.path.join(
    REPO, "crates", "asura-world", "src", "load_fixture.rs"
)

LINE_RE = re.compile(r"\b(SEND|RECV)\s+0x([0-9A-Fa-f]{4})\s+(\d+)\s+bytes\s*:\s*([0-9A-Fa-f ]*)")

# Periodic traffic, by the reference's own tier: "N -- Noise: periodic by design: ticks, heartbeats,
# ping. Must be *understood*, never 'fixed'" (`PreSearing/docs/07-packet-scope.md`). A load stream dump
# has no ticker in it, so comparing these would measure the clock rather than the block.
PERIODIC = {0x000C, 0x000D, 0x001E}


def parse(text, direction="SEND", drop_periodic=False):
    """Every (header, size) of one direction, in the order it appears."""
    messages = []
    for line in text.splitlines():
        match = LINE_RE.search(line)
        if not match or match.group(1) != direction:
            continue
        header = int(match.group(2), 16)
        if drop_periodic and header in PERIODIC:
            continue
        messages.append((header, int(match.group(3))))
    return messages


def align(ours, theirs):
    """Walk our stream, matching each message to the next reference one with the same header."""
    reference_at = {}
    for index, (header, _size) in enumerate(theirs):
        reference_at.setdefault(header, []).append(index)

    matched = []  # (ours_index, reference_index)
    used = set()
    cursor = 0
    for our_index, (header, _size) in enumerate(ours):
        candidates = reference_at.get(header, [])
        for candidate in candidates:
            if candidate in used or candidate < cursor:
                continue
            matched.append((our_index, candidate))
            used.add(candidate)
            cursor = candidate
            break
    return matched, used


def measure(ours, theirs):
    matched, used = align(ours, theirs)
    sizes = []
    for our_index, reference_index in matched:
        our_size = ours[our_index][1]
        reference_size = theirs[reference_index][1]
        if our_size != reference_size:
            sizes.append((ours[our_index][0], our_size, reference_size))
    matched_headers = {theirs[index][0] for index in used}
    missing = [message for message in theirs if message[0] not in matched_headers]
    extra = [message for message in ours if message[0] not in {reference[0] for reference in theirs}]
    return {
        "matched": len(matched),
        "missing": missing,
        "extra": extra,
        "sizes": sizes,
    }


def ours_from_dump(quiet=False):
    command = [
        "cargo",
        "run",
        "--quiet",
        "-p",
        "asura-world",
        "--example",
        "dump-load",
    ]
    if quiet:
        output = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    else:
        output = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    if output.returncode != 0:
        sys.exit("the dump example failed:\n%s" % output.stderr)
    return output.stdout


def fixture_text(result):
    """The measurement as a Rust constant: headers and sizes, nothing that could carry a name or an id."""
    lines = [
        "//! Generated by `tools/parity-load.py --fixture`. Do not edit by hand.",
        "//!",
        "//! The load stream the reference sends, as `(header, size)` pairs in order, measured from its own",
        "//! `GWPS_TRACE=1` log. Header and length only: no payload, no name, no id, so this can live in the",
        "//! repository while the capture it came from cannot.",
        "",
        "/// `(header, size)` in the order the reference sends them.",
        "pub const REFERENCE_LOAD: &[(u16, usize)] = &[",
    ]
    for header, size in result["reference"]:
        lines.append("    (0x%04X, %d)," % (header, size))
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference", default=DEFAULT_REFERENCE, help="the GWPS trace")
    parser.add_argument("--ours", help="our dump; omit to run the example")
    parser.add_argument("--fixture", default=None, help="write the reference stream as a Rust constant")
    parser.add_argument("--check", default=None, help="fail if the fixture on disk is out of date")
    args = parser.parse_args()

    if not os.path.exists(args.reference):
        sys.stderr.write("no reference trace at %s\n" % args.reference)
        return 2

    theirs = parse(
        open(args.reference, encoding="utf-8", errors="replace").read(), drop_periodic=True
    )
    ours = parse(args.ours if args.ours else ours_from_dump(), drop_periodic=True)
    result = measure(ours, theirs)
    result["reference"] = theirs

    write = sys.stdout.write
    write("reference messages: %d\n" % len(theirs))
    write("ours:               %d\n" % len(ours))
    write("matched:            %d\n" % result["matched"])
    write("missing:            %d\n" % len(result["missing"]))
    write("extra:              %d\n" % len(result["extra"]))
    write("size disagreements: %d\n" % len(result["sizes"]))

    if result["missing"]:
        write("\nMISSING -- the reference sends these and this server does not\n")
        for header, size in result["missing"]:
            write("  0x%04X  %d bytes\n" % (header, size))
    if result["extra"]:
        write("\nEXTRA -- this server sends these and the reference does not\n")
        for header, size in result["extra"]:
            write("  0x%04X  %d bytes\n" % (header, size))
    if result["sizes"]:
        write("\nSIZE -- both send it, at different lengths\n")
        for header, ours_size, theirs_size in result["sizes"]:
            write("  0x%04X  ours %d, reference %d\n" % (header, ours_size, theirs_size))

    path = args.fixture or args.check
    if path:
        generated = fixture_text(result)
        if args.check:
            if not os.path.exists(path):
                sys.stderr.write("no fixture at %s to check\n" % path)
                return 1
            on_disk = open(path, encoding="utf-8").read()
            if on_disk != generated:
                sys.stderr.write(
                    "the load fixture is out of date with the reference; regenerate with "
                    "--fixture %s\n" % path
                )
                return 1
            write("\nfixture is current: %s\n" % path)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(generated)
            write("\nwrote %s\n" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
