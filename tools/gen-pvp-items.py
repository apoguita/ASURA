#!/usr/bin/env python3
"""Generate crates/asura-protocol/src/game/pvp_items.rs from the GWPS reference.

Why generate: `GameSrv_SendPvpItems` sends 389 `GAME_SMSG_PVP_ITEM_STREAM_ADD` messages whose
contents are a fixed table of unlockable PvP items, written out as C literals in `GameSrv.c`. They are
data the client builds a table from, not something this project can derive -- and retyping 389 rows of
hex by hand is how a wrong constant gets into the client's item list. Reading them out of the
reference is the same rule the two message tables follow.

Source: `code/OpenTyria/GameSrv.c`, `GameSrv_SendPvpItems`, the `static PvpItem items[]` array:
`{ id, n_param, { params... } }`.

Usage:
  python tools/gen-pvp-items.py [--gwps C:\\path\\to\\PreSearing] [--out PATH] [--check]

  --check exits non-zero if the generated file would differ from what is on disk.

This file stays ASCII-only, like every other script in tools/ (docs/HANDOFF.md).
"""

import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GWPS = os.path.join(os.path.dirname(REPO), "PreSearing")
DEFAULT_OUT = os.path.join(REPO, "crates", "asura-protocol", "src", "game", "pvp_items.rs")

ENTRY_RE = re.compile(
    r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*\{([^}]*)\}\s*\}"
)


def find_array(text):
    """The text of the `items[]` array inside `GameSrv_SendPvpItems`."""
    start = text.find("void GameSrv_SendPvpItems")
    if start < 0:
        raise SystemExit("gen-pvp-items: GameSrv_SendPvpItems is not in GameSrv.c")
    array_start = text.find("static PvpItem items[] = {", start)
    if array_start < 0:
        raise SystemExit("gen-pvp-items: the items[] array moved or was renamed")
    end = text.find("\n    };", array_start)
    if end < 0:
        raise SystemExit("gen-pvp-items: the items[] array has no end")
    return text[array_start:end]


def parse(text):
    entries = []
    seen = set()
    for match in ENTRY_RE.finditer(text):
        item_id = int(match.group(1))
        n_param = int(match.group(2))
        params = [value.strip() for value in match.group(3).split(",") if value.strip()]
        if len(params) != n_param:
            raise SystemExit(
                "gen-pvp-items: item %d declares %d params but has %d"
                % (item_id, n_param, len(params))
            )
        if item_id in seen:
            raise SystemExit(
                "gen-pvp-items: item id %d appears twice" % item_id
            )
        seen.add(item_id)
        entries.append((item_id, params))
    if not entries:
        raise SystemExit("gen-pvp-items: no entries parsed")
    # The ids are the client's own item ids and they are **not** 1..n: the reference's table skips some
    # (entry 20 carries id 22). They are carried through verbatim, and only uniqueness is enforced.
    return entries


def render(entries):
    lines = []
    lines.append("//! The PvP item unlock table, generated from the GWPS reference. DO NOT EDIT BY HAND.")
    lines.append("//!")
    lines.append("//! Generated by `tools/gen-pvp-items.py` from `code/OpenTyria/GameSrv.c`,")
    lines.append("//! `GameSrv_SendPvpItems`: the `items[]` array, %d entries." % len(entries))
    lines.append("//!")
    lines.append("//! The reference sends one `GAME_SMSG_PVP_ITEM_STREAM_ADD` per entry, then")
    lines.append("//! `GAME_SMSG_PVP_ITEM_STREAM_END`. The client builds its unlockable-PvP-item table from")
    lines.append("//! them, which is why they are copied rather than invented: an empty stream is a table the")
    lines.append("//! client does not have.")
    lines.append("//!")
    lines.append("//! Regenerate with `python tools/gen-pvp-items.py`; verify with `--check`.")
    lines.append("")
    lines.append("/// One unlockable PvP item: its id and the parameters the client pairs with it.")
    lines.append("pub struct PvpItem {")
    lines.append("    pub id: u16,")
    lines.append("    pub params: &'static [u32],")
    lines.append("}")
    lines.append("")
    lines.append("/// Every unlockable PvP item, in the reference's order.")
    lines.append("pub const PVP_ITEMS: &[PvpItem] = &[")
    for item_id, params in entries:
        lines.append("    PvpItem {")
        lines.append("        id: %d," % item_id)
        body = ", ".join(params)
        lines.append("        params: &[%s]," % body)
        lines.append("    },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gwps", default=DEFAULT_GWPS)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    source = os.path.join(args.gwps, "code", "OpenTyria", "GameSrv.c")
    if not os.path.exists(source):
        raise SystemExit("gen-pvp-items: no reference checkout at %s" % source)

    import io

    with io.open(source, "r", encoding="utf-8", errors="replace") as handle:
        text = handle.read()

    entries = parse(find_array(text))
    rendered = render(entries)

    if args.check:
        if not os.path.exists(args.out):
            raise SystemExit("gen-pvp-items: %s is missing; run the generator" % args.out)
        with io.open(args.out, "r", encoding="utf-8") as handle:
            existing = handle.read()
        if existing != rendered:
            raise SystemExit("gen-pvp-items: %s is stale; run the generator" % args.out)
        print("up to date: %s (%d entries)" % (args.out, len(entries)))
        return

    with io.open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    print("wrote %s (%d entries)" % (args.out, len(entries)))


if __name__ == "__main__":
    main()
