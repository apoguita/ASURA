#!/usr/bin/env python3
"""Generate crates/asura-protocol/src/game/default_inventory.rs from a GWPS trace.

Why: a client that receives no items at all has no inventory model, and dies when it tries to draw the
character it just created. GWPS seeds every character it loads with a fixed set -- a backpack with a
bag item, a cupcake, and six pieces of equipment in the equipped-items bag -- and those items are what
its `GAME_SMSG_CREATE_NAMED_ITEM` / `ITEM_MOVED_TO_LOCATION` / `ITEM_SET_PROFESSION` messages carry.

This project has no item system yet, so the honest thing is to send the reference's own messages
verbatim, from a trace of it working, rather than to invent items with made-up file ids. When the item
system arrives these become rows; the ids stay the ones the capture used, and this file is where they
are recorded.

Source: a full GWPS trace (`GWPS_TRACE=1`, see tools/patch-gwps-full-trace.py), specifically the
messages the world server sends between the client's item request (`RECV 0x8091`) and its spawn
request (`RECV 0x8088`), filtered to the item family.

Usage:
  python tools/gen-default-inventory.py --capture C:\\path\\gwps-capture.log [--out PATH] [--check]

This file stays ASCII-only (docs/HANDOFF.md).
"""

import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(
    REPO, "crates", "asura-protocol", "src", "game", "default_inventory.rs"
)

STEP_RE = re.compile(
    r"(SEND|RECV) 0x([0-9A-Fa-f]{4})\s+(\d+) bytes\s*:\s*([0-9A-Fa-f ]*)"
)

# The item family: bags, items, placements, professions. Everything else in that window is a message
# this project already sends itself and is left to the world server.
ITEM_HEADERS = (0x013F, 0x0161, 0x013E, 0x015A)

EQUIPPED_BAG_ID = 5


def steps(text):
    for line in text.splitlines():
        match = STEP_RE.search(line)
        if not match:
            continue
        kind = match.group(1)
        header = int(match.group(2), 16)
        size = int(match.group(3))
        data = bytes(int(part, 16) for part in match.group(4).split())
        if len(data) != size:
            raise SystemExit(
                "gen-default-inventory: a %d-byte message parsed as %d bytes"
                % (size, len(data))
            )
        yield kind, header, data


def item_window(text):
    """The item-family messages the world sent while answering the client's item request."""
    collecting = False
    window = []
    for kind, header, data in steps(text):
        if kind == "RECV" and header == 0x8091:
            collecting = True
            continue
        if collecting and kind == "RECV":
            break  # the next request ends the window
        if collecting and header in ITEM_HEADERS:
            window.append((header, data))
    if not window:
        raise SystemExit(
            "gen-default-inventory: no item messages found; is the trace from a real session?"
        )
    return window


def equipped_ids(window):
    """The item ids in the equipped-items bag, by slot, as the agent's visual equipment needs them."""
    ids = [0] * 9
    for header, data in window:
        if header != 0x013E:
            continue
        # stream_id(2) item_id(4) bag_id(2) slot(1)
        item_id = int.from_bytes(data[4:8], "little")
        bag_id = int.from_bytes(data[8:10], "little")
        slot = data[10]
        if bag_id != EQUIPPED_BAG_ID or slot >= len(ids):
            continue
        ids[slot] = item_id
    if not any(ids):
        raise SystemExit(
            "gen-default-inventory: bag %d has no items in this trace" % EQUIPPED_BAG_ID
        )
    return ids


def render(window, ids):
    lines = []
    lines.append("//! The default character inventory, generated from a GWPS trace. DO NOT EDIT BY HAND.")
    lines.append("//!")
    lines.append("//! Generated by `tools/gen-default-inventory.py` from a full-byte trace of the")
    lines.append("//! reference (`GWPS_TRACE=1`) working: the `CREATE_NAMED_ITEM`, `INVENTORY_CREATE_BAG`,")
    lines.append("//! `ITEM_MOVED_TO_LOCATION` and `ITEM_SET_PROFESSION` messages it sends for the character")
    lines.append("//! it loads. %d messages." % len(window))
    lines.append("//!")
    lines.append("//! Why copy rather than invent: a client given no items has no inventory model and dies")
    lines.append("//! when it draws the character it has just created. These are the reference's own items,")
    lines.append("//! with its own ids and file ids, so the wire is identical to what a working server")
    lines.append("//! sends. When this project has an item system these become rows in a table; the ids")
    lines.append("//! below are the ones the capture used, kept here so that can be checked.")
    lines.append("//!")
    lines.append("//! Regenerate with `python tools/gen-default-inventory.py --capture <trace>`; verify with")
    lines.append("//! `--check`.")
    lines.append("")
    lines.append("/// The reference's item messages for its default character, in its order.")
    lines.append("///")
    lines.append("/// Each entry is a whole message: the header, then the body. They are replayed as they are,")
    lines.append("/// because every field in them (file ids, models, names, placement) is the reference's own")
    lines.append("/// data rather than something this project can derive.")
    lines.append("pub const DEFAULT_INVENTORY: &[(u16, &[u8])] = &[")
    for header, data in window:
        body = ", ".join("0x%02X" % byte for byte in data[2:])
        lines.append("    (0x%04X, &[%s])," % (header, body))
    lines.append("];")
    lines.append("")
    lines.append("/// The item ids in the equipped-items bag, by slot: what `UPDATE_AGENT_VISUAL_EQUIPMENT`")
    lines.append("/// carries, and what makes a character visible with its armour on.")
    lines.append("pub const EQUIPPED_ITEM_IDS: [u32; 9] = [%s];" % ", ".join(str(i) for i in ids))
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--capture", required=True, help="a full GWPS trace")
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    import io

    text = io.open(args.capture, encoding="utf-8", errors="replace").read()
    window = item_window(text)
    ids = equipped_ids(window)
    rendered = render(window, ids)

    if args.check:
        if not os.path.exists(args.out):
            raise SystemExit("gen-default-inventory: %s is missing" % args.out)
        existing = io.open(args.out, encoding="utf-8").read()
        if existing != rendered:
            raise SystemExit("gen-default-inventory: %s is stale" % args.out)
        print("up to date: %s (%d messages)" % (args.out, len(window)))
        return

    io.open(args.out, "w", encoding="utf-8", newline="\n").write(rendered)
    print("wrote %s (%d messages, equipped ids %s)" % (args.out, len(window), ids))


if __name__ == "__main__":
    main()
