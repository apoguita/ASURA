#!/usr/bin/env python3
"""Generate the decompressor's static tables from the reference's `FaCompress.c`.

Six tables, all data, all easy to get wrong by hand: `Table1` (the prefix ranges), `Table2` (the run
descriptor), `Table3` (back-reference bases), `s_extraBitsLength`, `s_extraBitsDistance` and `BacktrackTable`.
The first attempt at this port transcribed `Table1` from memory and produced values that do not exist in the
reference at all -- which is exactly the failure mode the generators in this repository exist to prevent.

Usage:
  python tools/gen-fa-compress-tables.py [--gwps PATH] [--out PATH] [--check]

This file stays ASCII-only (docs/HANDOFF.md).
"""

import argparse
import io
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_GWPS = os.path.join(os.path.dirname(REPO), "PreSearing")
DEFAULT_OUT = os.path.join(REPO, "crates", "asura-world", "src", "fa_compress_tables.rs")


def read(path):
    with io.open(path, "r", encoding="utf-8", errors="replace") as handle:
        return handle.read()


def braced(text, start):
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : index]
    raise SystemExit("unbalanced braces")


def scalar_table(text, declaration, rust_type, count_expected=None):
    """`<declaration> = { 0x00, 0x01, ... };` -> the values, as Rust literals."""
    start = text.index(declaration)
    body = braced(text, text.index("{", start))
    values = re.findall(r"0x[0-9A-Fa-f]+|\d+", body)
    if count_expected is not None and len(values) != count_expected:
        raise SystemExit(
            "%s has %d values, expected %d" % (declaration, len(values), count_expected)
        )
    return "%s: [%s; %d]" % (declaration, ", ".join(values), len(values))


def table1(text):
    start = text.index("Table1Type Table1[")
    body = braced(text, text.index("{", start))
    pairs = re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(\d+)\s*\}", body)
    if not pairs:
        raise SystemExit("Table1 has no pairs")
    entries = ", ".join("(%s, %s)" % pair for pair in pairs)
    return "TABLE1: [(u32, u32); %d]" % len(pairs), entries, len(pairs)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gwps", default=DEFAULT_GWPS)
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    path = os.path.join(args.gwps, "code", "OpenTyria", "FaCompress.c")
    if not os.path.exists(path):
        sys.stderr.write("no reference at %s\n" % path)
        return 2
    text = read(path)

    table1_type, table1_values, table1_count = table1(text)

    declaration, entries, count = table1_type, table1_values, table1_count
    lines = [
        "//! Generated by `tools/gen-fa-compress-tables.py` from the reference's `FaCompress.c`. Do not edit.",
        "//!",
        "//! These are the decompressor's own tables. They are data, not something derivable from the format, so",
        "//! they are read out of the reference rather than typed: the first hand transcription of `Table1`",
        "//! produced values that appear nowhere in the reference.",
        "",
        "/// `Table1` (`FaCompress.c`): `(FirstEncoding, LastIndex)` prefix ranges for a code-length run.",
        "pub const %s = [%s];" % (declaration, entries),
        "",
    ]

    scalars = [
        ("Table2", "TABLE2", "u8", 256),
        ("Table3", "TABLE3", "u8", 32),
        ("s_extraBitsLength", "EXTRA_BITS_LENGTH", "u8", 29),
        ("s_extraBitsDistance", "EXTRA_BITS_DISTANCE", "u8", 32),
        ("BacktrackTable", "BACKTRACK", "u16", 46),
    ]

    for c_name, rust_name, rust_type, expected in scalars:
        # Find the declaration line, then the braces after it.
        match = re.search(r"\b%s\s*\[[^\]]*\]\s*=\s*\{" % re.escape(c_name), text)
        if not match:
            raise SystemExit("no %s in the reference" % c_name)
        body = braced(text, match.end() - 1)
        values = re.findall(r"0x[0-9A-Fa-f]+|\d+", body)
        if len(values) != expected:
            raise SystemExit(
                "%s has %d values, expected %d" % (c_name, len(values), expected)
            )
        lines.append("/// `%s` (`FaCompress.c`)." % c_name)
        lines.append(
            "pub const %s: [%s; %d] = [%s];"
            % (rust_name, rust_type, len(values), ", ".join(values))
        )
        lines.append("")

    generated = "\n".join(lines)

    # rustfmt reflows these long arrays, so the file on disk is the formatted form. Formatting the
    # generated text the same way is what makes --check a comparison of content rather than of layout.
    def formatted(text_of_file):
        import tempfile

        with tempfile.NamedTemporaryFile(
            "w", suffix=".rs", delete=False, encoding="utf-8", newline="\n"
        ) as handle:
            handle.write(text_of_file)
            temporary = handle.name
        try:
            subprocess.run(
                ["rustfmt", "--edition", "2021", temporary], check=True, capture_output=True
            )
            return read(temporary)
        finally:
            os.unlink(temporary)

    generated = formatted(generated)

    if args.check:
        if not os.path.exists(args.out):
            sys.stderr.write("no generated file at %s\n" % args.out)
            return 1
        if formatted(read(args.out)) != generated:
            sys.stderr.write(
                "the decompressor tables are out of date with the reference; regenerate with "
                "python tools/gen-fa-compress-tables.py\n"
            )
            return 1
        print("the decompressor tables are current: %s" % args.out)
        return 0

    with io.open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generated)
    print("wrote %s: Table1 %d pairs, five scalar tables" % (args.out, table1_count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
