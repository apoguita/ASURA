# Temporary-trust recovery for a PostgreSQL install whose superuser password is unknown.
#
# What it does, in order:
#   1. backs up pg_hba.conf
#   2. temporarily replaces scram-sha-256 with trust on local/loopback lines
#   3. restarts the service, so the superuser can connect without a password
#   4. sets a fresh superuser password, creates the asura role and database
#   5. restores the original pg_hba.conf and restarts again (secure auth back on)
#   6. applies the ASURA schema as the asura role and lists what exists
#   7. writes ASURA\.env with the generated passwords (that file is gitignored)
#
# ASCII only: Windows PowerShell 5.1 reads a BOM-less file as ANSI, and a UTF-8 em dash or curly
# quote decodes to a smart quote, which PowerShell treats as a string delimiter and fails to parse.

$ErrorActionPreference = "Stop"
$log = "C:\Users\Apo\Documents\GitHub\PreSearing\build\pg-setup.log"
Start-Transcript -Path $log -Force | Out-Null

try {
    $data    = "C:\Program Files\PostgreSQL\16\data"
    $hba     = Join-Path $data "pg_hba.conf"
    $service = "postgresql-x64-16"
    $psql    = "C:\Program Files\PostgreSQL\16\bin\psql.exe"
    $schema  = "C:\Users\Apo\Documents\GitHub\ASURA\crates\asura-db\migrations\0001_init.sql"
    $envFile = "C:\Users\Apo\Documents\GitHub\ASURA\.env"

    foreach ($p in @($hba, $psql, $schema)) {
        if (-not (Test-Path $p)) { throw "missing: $p" }
    }

    $stamp  = Get-Date -Format "yyyyMMdd-HHmmss"
    $backup = "$hba.bak-$stamp"
    Copy-Item $hba $backup -Force
    Write-Host "backed up pg_hba.conf to $backup"

    (Get-Content $hba) -replace 'scram-sha-256', 'trust' | Set-Content $hba -Encoding ASCII
    Restart-Service $service
    Start-Sleep -Seconds 4
    Write-Host "service restarted with temporary trust auth"

    function Invoke-Sql {
        param([string] $Sql, [string] $User = "postgres", [string] $Db = "")
        $target = @("-U", $User, "-h", "127.0.0.1", "-p", "5432", "-v", "ON_ERROR_STOP=1", "-X", "-A", "-t")
        if ($Db) { $target += @("-d", $Db) }
        $target += @("-c", $Sql)
        $out = & $psql @target 2>&1
        if ($LASTEXITCODE -ne 0) { throw "psql failed ($LASTEXITCODE) for: $Sql`n$out" }
        return ($out -join "`n").Trim()
    }

    $chars = 48..57 + 65..90 + 97..122
    $pgPassword    = -join (1..28 | ForEach-Object { [char](Get-Random -InputObject $chars) })
    $asuraPassword = -join (1..28 | ForEach-Object { [char](Get-Random -InputObject $chars) })

    Invoke-Sql -Sql "ALTER ROLE postgres PASSWORD '$pgPassword'" | Out-Null
    Write-Host "set a new superuser password (recorded in .env)"

    $roleExists = Invoke-Sql -Sql "SELECT 1 FROM pg_roles WHERE rolname = 'asura'"
    if ($roleExists -eq "1") {
        Invoke-Sql -Sql "ALTER ROLE asura LOGIN PASSWORD '$asuraPassword'" | Out-Null
        Write-Host "role asura existed; password reset"
    } else {
        Invoke-Sql -Sql "CREATE ROLE asura LOGIN PASSWORD '$asuraPassword'" | Out-Null
        Write-Host "created role asura"
    }

    $dbExists = Invoke-Sql -Sql "SELECT 1 FROM pg_database WHERE datname = 'asura'"
    if ($dbExists -eq "1") {
        Write-Host "database asura already exists"
    } else {
        Invoke-Sql -Sql "CREATE DATABASE asura OWNER asura" | Out-Null
        Write-Host "created database asura"
    }

    Copy-Item $backup $hba -Force
    Restart-Service $service
    Start-Sleep -Seconds 4
    Write-Host "restored pg_hba.conf; scram-sha-256 is back on"

    # The .env file is written before verification so the credentials survive a failure below.
    @(
        "# Local development credentials. Gitignored. Generated by the PostgreSQL recovery script.",
        "ASURA_DATABASE_URL=postgres://asura:$asuraPassword@127.0.0.1:5432/asura",
        "ASURA_DB_ROLE=asura",
        "ASURA_DB_PASSWORD=$asuraPassword",
        "PGPASSWORD_SUPERUSER=$pgPassword",
        "ASURA_DB_NAME=asura",
        "ASURA_DB_HOST=127.0.0.1",
        "ASURA_DB_PORT=5432"
    ) | Set-Content $envFile -Encoding ASCII
    Write-Host "wrote $envFile"

    $env:PGPASSWORD = $asuraPassword
    & $psql -U asura -d asura -h 127.0.0.1 -v ON_ERROR_STOP=1 -X -f $schema
    if ($LASTEXITCODE -ne 0) { throw "could not apply the schema" }
    Write-Host "applied the schema"

    Write-Host ""
    Write-Host "tables:"
    & $psql -U asura -d asura -h 127.0.0.1 -X -A -t -c "SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename"

    Write-Host ""
    Write-Host "pool invariants present:"
    & $psql -U asura -d asura -h 127.0.0.1 -X -A -t -c "SELECT conname FROM pg_constraint WHERE conname LIKE 'world_pool%' ORDER BY conname"

    Write-Host ""
    Write-Host "DONE"
}
catch {
    Write-Host "FAILED: $($_.Exception.Message)"
}
finally {
    $env:PGPASSWORD = $null
    Stop-Transcript | Out-Null
}
